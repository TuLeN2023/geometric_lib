
def area(a):
    '''
    Возвращает площадь квадрата со стороной a
    Параметры:
        a (float) - сторона
    Возвращаемое значение:
        a*a - площадь
    Пример вызова:
    >>> area(2)
    4
    '''
    return a * a

def perimeter(a):
    '''
    Возвращает периметр квадрата со стороной a
    Параметры:
        a (float) - сторона
    Возвращаемое значение:
        4*a - периметр
    Пример вызова:
    >>> perimeter(3)
    12
    '''
    return 4 * a
